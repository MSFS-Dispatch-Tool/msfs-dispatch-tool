"""SimBrief's API v2, called with the pilot's own Navigraph sign-in.

Each call carries the pilot's access token (navigraph.py and
app.navigraph_access_token keep it current), so it only ever reaches that
pilot's own SimBrief account.

    GET  /v2/flightplans/latest   the pilot's most recent flight plan (OFP)
    GET  /v2/airframes/user/mine  the pilot's saved airframes
    POST /v2/plan/generate        a new flight plan; answers with the OFP

Plan generation isn't in Navigraph's public documentation; what it
accepts was worked out against the live API: form fields with the classic
dispatch option names, the departure time inside the date.

Navigraph's documentation: https://developers.navigraph.com/docs/simbrief
"""
import os

import requests

BASE_URL = (os.environ.get("SIMBRIEF_API_URL") or "https://api.simbrief.com").rstrip("/")
TIMEOUT_SECONDS = 20


class SimBriefError(Exception):
    """SimBrief refused or couldn't be reached. The message is safe to show;
    reconnect means the Navigraph sign-in no longer works for SimBrief."""

    def __init__(self, message, reconnect=False, status=None):
        super().__init__(message)
        self.reconnect = reconnect
        self.status = status


def _get(path, access_token, missing):
    try:
        resp = requests.get(BASE_URL + path, timeout=TIMEOUT_SECONDS,
                            headers={"Authorization": f"Bearer {access_token}", "Accept": "application/json"})
    except requests.RequestException:
        raise SimBriefError("SIMBRIEF NOT AVAILABLE. RETRY IN 1 MIN")
    if resp.status_code in (401, 403):
        raise SimBriefError("NAVIGRAPH SIGN-IN NOT ACCEPTED BY SIMBRIEF. SIGN IN WITH NAVIGRAPH AGAIN",
                            reconnect=True, status=resp.status_code)
    if resp.status_code == 404:
        raise SimBriefError(missing, status=404)
    if resp.status_code != 200:
        raise SimBriefError(f"SIMBRIEF ERROR (HTTP {resp.status_code})", status=resp.status_code)
    try:
        return resp.json()
    except ValueError:
        raise SimBriefError("SIMBRIEF RESPONSE NOT READABLE", status=resp.status_code)


def latest_plan(access_token):
    """The pilot's most recent flight plan, as SimBrief returns it."""
    return _get("/v2/flightplans/latest", access_token, "NO OFP ON SIMBRIEF ACCOUNT")


def user_airframes(access_token):
    """The airframes the pilot has saved on SimBrief, as SimBrief returns them."""
    return _get("/v2/airframes/user/mine", access_token, "NO SAVED AIRFRAMES ON SIMBRIEF ACCOUNT")


_MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")


def departure_date(when):
    """The departure date and time (UTC) the way plan generation reads it:
    "2 Nov 2026 - 14:30". Separate hour fields (deph/depm, dephour/depmin)
    are ignored by the API: the plan would leave at 00:00Z."""
    return f"{when.day} {_MONTHS[when.month - 1]} {when.year} - {when.hour:02d}:{when.minute:02d}"


def generate(access_token, params):
    """Generates a plan with SimBrief's classic dispatch options, sent as
    form fields, and returns the OFP it answers with (same format as
    latest_plan). "type" can be an ICAO type or one of the pilot's saved
    airframes' internal IDs."""
    try:
        resp = requests.post(BASE_URL + "/v2/plan/generate", data=params, timeout=60,
                             headers={"Authorization": f"Bearer {access_token}", "Accept": "application/json"})
    except requests.RequestException:
        raise SimBriefError("SIMBRIEF NOT AVAILABLE. RETRY IN 1 MIN")
    if resp.status_code in (401, 403):
        raise SimBriefError("NAVIGRAPH SIGN-IN NOT ACCEPTED BY SIMBRIEF. SIGN IN WITH NAVIGRAPH AGAIN",
                            reconnect=True, status=resp.status_code)
    try:
        data = resp.json()
    except ValueError:
        data = None
    if resp.status_code == 200 and isinstance(data, dict) and isinstance(data.get("general"), dict):
        return data
    reason = ""
    if isinstance(data, dict):
        reason = str(data.get("error") or data.get("message") or "")[:200]
    raise SimBriefError(f"OFP NOT GENERATED BY SIMBRIEF ({str(reason).upper() if reason else f'HTTP {resp.status_code}'})",
                        status=resp.status_code)
